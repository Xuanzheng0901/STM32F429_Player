#ifndef USB_AUDIO_FORMAT_H
#define USB_AUDIO_FORMAT_H

/* USB 描述符、PCM 通路和 UI 共用固定格式；PCM 为小端有符号整数。 */
#define USB_AUDIO_SAMPLE_RATE 96000U
#define USB_AUDIO_CHANNELS 2U
#define USB_AUDIO_SAMPLE_BYTES 4U
#define USB_AUDIO_BITS (USB_AUDIO_SAMPLE_BYTES * 8U)
#define USB_AUDIO_FRAME_BYTES (USB_AUDIO_CHANNELS * USB_AUDIO_SAMPLE_BYTES)
#define USB_AUDIO_FRAMES_PER_MS (USB_AUDIO_SAMPLE_RATE / 1000U)
/* 给每毫秒多一帧留出余量，允许 95/96/97 帧的数据包。 */
#define USB_AUDIO_MAX_PACKET_BYTES ((USB_AUDIO_FRAMES_PER_MS + 1U) * USB_AUDIO_FRAME_BYTES)

#endif
